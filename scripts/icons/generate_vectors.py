#!/usr/bin/env python3
"""Reproduce approved compact and monochrome Android vectors. Uses the reviewed path bounds shipped with the source."""
from pathlib import Path
import xml.etree.ElementTree as ET
import json
import re
from decimal import Decimal, ROUND_HALF_EVEN
ROOT = Path(__file__).resolve().parents[2]
BOUNDS = json.loads((ROOT/'design/icons-v3/path-bounds.json').read_text())
A = 'http://schemas.android.com/apk/res/android'
APT = 'http://schemas.android.com/aapt'
ET.register_namespace('android', A)
ET.register_namespace('aapt', APT)
def attrs(**values): return {f'{{{A}}}{k}': str(v) for k,v in values.items()}
def color(value, opacity='1'):
    return '#' + f'{round(float(opacity)*255):02X}' + value.removeprefix('#').upper()
def shape(node):
    tag = node.tag.split('}')[-1]
    if tag == 'path': return node.get('d')
    if tag == 'circle':
        x,y,r = map(float, (node.get('cx'),node.get('cy'),node.get('r')))
        return f'M{x-r} {y}a{r} {r} 0 1 0 {2*r} 0a{r} {r} 0 1 0 {-2*r} 0Z'
    x,y,w,h,r = map(float, (node.get('x'),node.get('y'),node.get('width'),node.get('height'),node.get('rx','0')))
    return f'M{x+r} {y}H{x+w-r}a{r} {r} 0 0 1 {r} {r}V{y+h-r}a{r} {r} 0 0 1 {-r} {r}H{x+r}a{r} {r} 0 0 1 {-r} {-r}V{y+r}a{r} {r} 0 0 1 {r} {-r}Z'
# Round only absolute point coordinates. Relative/arc parameters stay byte-for-byte
# unchanged, avoiding accumulated relative drift or arc-radius perturbations.
NUMBER = re.compile(r"[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?")
COMMAND = re.compile(r"([MmLlHhVvCcSsQqTtAaZz])([^MmLlHhVvCcSsQqTtAaZz]*)")

def compact_path(data):
    def coordinates(match):
        command, args = match.groups()
        if command not in ('M', 'L', 'Q'):
            return match.group(0)
        def rounded(number):
            value = Decimal(number.group())
            result = value.quantize(Decimal('0.0001'), rounding=ROUND_HALF_EVEN)
            if result == value:
                return number.group()
            return format(result, 'f').rstrip('0').rstrip('.')
        return command + NUMBER.sub(rounded, args)
    return COMMAND.sub(coordinates, data)

def convert(source):
    svg=ET.parse(source).getroot()
    gradients={e.get('id'):e for e in svg.iter() if e.tag.endswith('linearGradient')}
    vector=ET.Element('vector', attrs(width='48dp',height='48dp',viewportWidth=48,viewportHeight=48,autoMirrored=str(source.stem=='back').lower()))
    def walk(node, parent, inherited):
        tag=node.tag.split('}')[-1]
        if tag in ('defs','title'): return
        style=dict(inherited); style.update(node.attrib)
        if tag in ('svg','g'):
            if node.get('transform') not in (None, 'translate(0 0) scale(1)', 'translate(1.4 0)'):
                raise ValueError('Unsupported transform: '+node.get('transform'))
            if tag=='g' and node.get('transform')=='translate(1.4 0)':
                parent=ET.SubElement(parent,'group',attrs(translateX='1.4'))
            for child in node: walk(child,parent,style)
            return
        if tag not in ('path','rect','circle'): raise ValueError(tag)
        d=shape(node)
        p=ET.SubElement(parent,'path',attrs(pathData=compact_path(d),fillType='evenOdd' if style.get('fill-rule')=='evenodd' else 'nonZero'))
        xmin,xmax,ymin,ymax=BOUNDS[d]
        for prop in ('fill','stroke'):
            value=style.get(prop,'#000000' if prop=='fill' else 'none')
            if value=='none' or (prop=='stroke' and float(style.get('stroke-width','1'))==0): continue
            field=prop+'Color'
            if value.startswith('url('):
                grad=gradients[value[5:-1]]
                item=ET.SubElement(p,f'{{{APT}}}attr',{'name':'android:'+field})
                g=ET.SubElement(item,'gradient',attrs(type='linear',startX=xmin,startY=ymin,endX=xmin,endY=ymax))
                for stop in grad:
                    ET.SubElement(g,'item',attrs(offset=stop.get('offset','0'),color=color(stop.get('stop-color'),stop.get('stop-opacity','1'))))
            else: p.set(f'{{{A}}}{field}',color(value,style.get(prop+'-opacity','1')))
            if prop=='stroke': p.set(f'{{{A}}}strokeWidth',style.get('stroke-width','1'))
    walk(svg,vector,{})
    ET.indent(vector)
    return '<?xml version="1.0" encoding="utf-8"?>\n<!-- CinemaTV approved V3; generated by scripts/icons/generate_vectors.py. -->\n'+ET.tostring(vector,encoding='unicode')+'\n'
if __name__=='__main__':
    for tier,folder in [('default','compact/default'),('selected','compact/selected'),('mono','monochrome')]:
        for source in sorted((ROOT/'design/icons-v3/svg'/folder).glob('*.svg')):
            (ROOT/f'app/src/main/res/drawable/cinema_v3_{source.stem}_{tier}.xml').write_text(convert(source))
