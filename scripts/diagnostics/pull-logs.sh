#!/usr/bin/env bash
# Pull the device-side diagnostic log directory into one local zip for review.
#
# Path one (normal): adb pull /sdcard/Android/data/<pkg>/files/diagnostics
# Path two (fallback): adb exec-out run-as <pkg> cat files/diagnostics/<name>
#   Used when external storage is not readable from the host shell (rare) or when the
#   export folder was never created (no export yet, only raw .jsonl files).
#
# Read-only toward the device: nothing is deleted, moved, or modified. Requires a
# debuggable build for path two only.
set -euo pipefail

PACKAGE=dev.cinematv
SERIAL=
OUT_DIR=
KEEP=0

usage() {
  cat <<'USAGE'
Usage: pull-logs.sh [--serial SERIAL] [--package PACKAGE] [--out DIR] [--keep]

  --serial   adb device serial, required only when several devices are attached.
  --package  application id (default: dev.cinematv).
  --out      directory for the produced zip (default: $TMPDIR).
  --keep     keep the unzipped working copy next to the zip.

Prints the absolute path of the created zip on success. Never prints log contents.
USAGE
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --serial) SERIAL=${2:?missing value for --serial}; shift 2 ;;
    --package) PACKAGE=${2:?missing value for --package}; shift 2 ;;
    --out) OUT_DIR=${2:?missing value for --out}; shift 2 ;;
    --keep) KEEP=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

command -v adb >/dev/null 2>&1 || { echo 'adb not found on PATH' >&2; exit 1; }
command -v python3 >/dev/null 2>&1 || { echo 'python3 not found on PATH' >&2; exit 1; }

adb_cmd() {
  if [ -n "$SERIAL" ]; then adb -s "$SERIAL" "$@"; else adb "$@"; fi
}

state=$(adb_cmd get-state 2>/dev/null || true)
[ "$state" = "device" ] || { echo "No usable adb device (state: ${state:-none})" >&2; exit 1; }

stamp=$(date +%Y%m%d-%H%M%S)
OUT_DIR=${OUT_DIR:-${TMPDIR:-/tmp}}
mkdir -p "$OUT_DIR"
work=$(mktemp -d "${TMPDIR:-/tmp}/cinematv-diag.XXXXXX")
trap 'rm -rf "$work"' EXIT

external="/sdcard/Android/data/$PACKAGE/files/diagnostics"
pulled=0
mkdir -p "$work/logs"

if adb_cmd shell "[ -d '$external' ]" >/dev/null 2>&1; then
  if adb_cmd pull "$external/." "$work/logs" >/dev/null 2>&1; then
    pulled=1
  fi
fi

if [ "$pulled" -eq 0 ]; then
  # Fallback: the internal files dir, readable with run-as on a debuggable build.
  if ! adb_cmd shell "run-as $PACKAGE ls files/diagnostics" >/dev/null 2>&1; then
    echo "Neither $external nor run-as access to files/diagnostics is available." >&2
    echo 'Enable diagnostics once, then export, or use a debuggable (dev) build.' >&2
    exit 1
  fi
  # Names are generated by the app (app-YYYYMMDD[-n].jsonl); still refuse anything
  # that is not a plain file name before using it in a shell word.
  adb_cmd shell "run-as $PACKAGE ls files/diagnostics" \
    | tr -d '\r' \
    | grep -E '^[A-Za-z0-9._-]+\.(jsonl|zip)$' \
    | while read -r name; do
        adb_cmd exec-out "run-as $PACKAGE cat files/diagnostics/$name" > "$work/logs/$name"
      done || true
  pulled=1
fi

if [ -z "$(find "$work" -type f -print -quit)" ]; then
  echo 'Diagnostic directories are empty; enable logging, reproduce, then retry.' >&2
  exit 1
fi

zip="$OUT_DIR/cinematv-diag-$stamp.zip"
python3 - "$work" "$zip" "$PACKAGE" <<'PY'
import os, sys, zipfile
work, target, package = sys.argv[1], sys.argv[2], sys.argv[3]
with zipfile.ZipFile(target, 'w', zipfile.ZIP_DEFLATED) as archive:
    for root, _, files in os.walk(work):
        for name in sorted(files):
            path = os.path.join(root, name)
            if os.path.getsize(path) == 0:
                continue
            archive.write(path, os.path.relpath(path, work))
    archive.writestr('README.txt', (
        f'package: {package}\n'
        'source: on-device diagnostics directory (user-initiated export only)\n'
        'note: no cookies, tokens, account ids, titles, episode names or raw pages.\n'
        'review locally before sharing; nothing is uploaded by this script.\n'))
PY

trap - EXIT
if [ "$KEEP" -eq 1 ]; then
  echo "working copy: $work"
else
  rm -rf "$work"
fi
echo "$zip"
